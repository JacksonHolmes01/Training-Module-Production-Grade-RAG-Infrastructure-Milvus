#!/usr/bin/env bash
# Write hardening/06-pinned.yml, which replaces every image TAG with the
# exact image DIGEST currently on this machine (the images you scanned).
#
# A tag like nginx:1.28 is a label that can be moved to different software.
# A digest like nginx@sha256:3f1c... is a fingerprint of one exact image.
set -euo pipefail
cd "$(dirname "$0")/.."

digest() {  # digest <image:tag>  ->  repo@sha256:...
  docker image inspect --format '{{index .RepoDigests 0}}' "$1" 2>/dev/null \
    || { docker pull -q "$1" >/dev/null && docker image inspect --format '{{index .RepoDigests 0}}' "$1"; }
}

MV=$(digest milvusdb/milvus:v3.0.5)
ET=$(digest quay.io/coreos/etcd:v3.5.25)
MI=$(digest milvusdb/minio:RELEASE.2024-12-18T13-15-44Z)
OL=$(digest ollama/ollama:0.40.6)
NG=$(digest nginxinc/nginx-unprivileged:1.28.2-alpine)
PY=$(digest python:3.12-slim)

cat > hardening/06-pinned.yml <<YAML
# Layer 6: every image pinned by digest (Lesson 9).
# Generated by bin/pin_images.sh on $(date -u +%Y-%m-%d). Re-run it (and re-scan)
# when you deliberately upgrade.
services:
  milvus:
    image: ${MV}
  storage-perms:
    image: ${MV}
  etcd:
    image: ${ET}
  minio:
    image: ${MI}
  ollama:
    image: ${OL}
  nginx:
    image: ${NG}
  ingestion-api:
    build:
      args:
        BASE_IMAGE: ${PY}
  milvus-init:
    build:
      args:
        BASE_IMAGE: ${PY}
  gradio-ui:
    build:
      args:
        BASE_IMAGE: ${PY}
YAML
echo "Wrote hardening/06-pinned.yml:"
grep -E 'image:|BASE_IMAGE' hardening/06-pinned.yml | sed 's/^ */  /'
