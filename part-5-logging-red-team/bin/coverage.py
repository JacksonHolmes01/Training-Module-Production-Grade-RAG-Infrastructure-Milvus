#!/usr/bin/env python3
"""
coverage.py: score the blue team. For each step of the latest red-team run,
did any detection fire while it was happening?

Usage (from the part-5 folder):
  python3 bin/coverage.py                  latest run, rules as they are now
  python3 bin/coverage.py --run redteam/runs/run-20261112-183000.json
  python3 bin/coverage.py --report         also write a findings report draft

Rules are applied to the logs again every time this runs, so after you
enable or tune a rule you can re-score the SAME campaign without re-attacking.
"""

import argparse
import json
import pathlib
import sys
from datetime import datetime, timedelta, timezone

from seclog import ROOT, detect, hhmmss, load_rules, read_events

GRACE = timedelta(seconds=5)  # logs can trail the action by a few seconds

ap = argparse.ArgumentParser()
ap.add_argument("--run")
ap.add_argument("--report", action="store_true")
args = ap.parse_args()

runs = sorted((ROOT / "redteam" / "runs").glob("run-*.json"))
if args.run:
    run_path = pathlib.Path(args.run)
elif runs:
    run_path = runs[-1]
else:
    sys.exit("No red-team runs found. Run python3 bin/redteam.py first.")
run = json.loads(run_path.read_text())

started = datetime.fromisoformat(run["started"])
# Only this run's events: an earlier run's alerts would otherwise put rules
# into their quiet period and hide this run's attacks.
since = (started - timedelta(seconds=5)).strftime("%Y-%m-%dT%H:%M:%SZ")
# Score ONLY the campaign's own events. Earlier practice traffic could
# otherwise put a rule in its quiet period and hide a campaign step.
events = [e for e in read_events(since) if e["ts"] >= started]
alerts = detect(events, load_rules())

rows, detected = [], 0
for step in run["steps"]:
    s, e = datetime.fromisoformat(step["start"]), datetime.fromisoformat(step["end"])
    # A step counts as detected only if a rule meant for that kind of attack
    # fired while it ran. An unrelated alert at the same moment is luck, not coverage.
    hits = [a for a in alerts
            if a["rule"] in step["expected_rules"] and s - timedelta(seconds=1) <= a["time"] <= e + GRACE]
    rows.append((step, hits))
    detected += bool(hits)

print(f"Run: {run_path.name}   Rules enabled: {', '.join(r['id'] for r in load_rules())}\n")
print(f"{'STEP':<5} {'ATTACK':<30} {'DETECTED':<9} ALERTS")
print("-" * 78)
for step, hits in rows:
    names = ", ".join(sorted({f'{a["rule"]} {a["name"]}' for a in hits})) or "-"
    print(f'{step["id"]:<5} {step["name"]:<30} {"YES" if hits else "no":<9} {names}')
print("-" * 78)
total = len(rows)
print(f"Detection coverage: {detected} of {total} attack steps ({100 * detected // total}%)")

if args.report:
    all_rules = {r["id"]: r for r in load_rules(include_disabled=True)}
    stamp = run_path.stem.replace("run-", "")
    out = ROOT / "redteam" / f"report-{stamp}.md"
    lines = [
        f"# Red Team Findings Report: {stamp}",
        "",
        "> Draft generated by bin/coverage.py. Review every section and rewrite it in your own words.",
        "",
        "## Summary",
        "",
        f"- Campaign: {len(rows)} steps, run {run['started'][:19].replace('T', ' ')} UTC",
        f"- Detection coverage: **{detected} of {total}** ({100 * detected // total}%)",
        f"- Alerts raised: {len(alerts)}",
        "",
        "## Results by step",
        "",
        "| Step | Attack | What the attacker saw | Detected | Alerts |",
        "|---|---|---|---|---|",
    ]
    for step, hits in rows:
        names = ", ".join(sorted({a["rule"] for a in hits})) or "none"
        lines.append(f'| {step["id"]} | {step["name"]} | {step["note"]} | {"yes" if hits else "**no**"} | {names} |')
    lines += ["", "## Findings (undetected steps)", ""]
    for step, hits in rows:
        if hits:
            continue
        expected = [all_rules[r] for r in step["expected_rules"] if r in all_rules]
        lines += [f'### {step["id"]}: {step["name"]}', "",
                  f'- **Technique:** {step["technique"]}',
                  f'- **What happened:** {step["note"]}']
        if expected:
            for r in expected:
                state = "disabled" if not r.get("enabled", True) else "enabled but did not fire"
                lines.append(f'- **Detection gap:** rule {r["id"]} "{r["name"]}" is {state}.')
        else:
            lines.append("- **Detection gap:** no rule covers this. The logs this lab collects cannot see it.")
        lines += ["- **Severity:** _your assessment_", "- **Recommendation:** _your recommendation_", ""]
    lines += ["## Alerts raised", "", "| Time (UTC) | Severity | Rule | Source | Count |", "|---|---|---|---|---|"]
    for a in alerts:
        lines.append(f'| {hhmmss(a["time"])} | {a["severity"]} | {a["rule"]} {a["name"]} | {a["group"]} | {a["count"]} |')
    lines += ["", "## Sign-off", "", "- Red team: ______", "- Blue team: ______", "- Date: ______", ""]
    out.write_text("\n".join(lines))
    print(f"\nReport draft written to {out.relative_to(ROOT)}")
